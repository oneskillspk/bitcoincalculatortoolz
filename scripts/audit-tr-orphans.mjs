async function walkComponents(dir) {
  try {
    const entries = await fs.readdir(dir, { withFileTypes: true });
    const files = [];
    for (const e of entries) {
      if (e.isFile() && e.name.endsWith('.tsx')) files.push(path.join(dir, e.name));
    }
    return files;
  } catch {
    return [];
  }
}

function classify(src) {
  const hasLang = /useLanguage|language\s*===|language===/.test(src);
  const hasT = /\bt\(['"]/.test(src);
  // Heuristic: a render with visible English JSX text — look for >text< between tags.
  const looksRendered = /<(h[1-6]|p|button|label|span|div)[^>]*>[A-Z][a-zA-Z][^<{]{6,}</.test(src);
  return { hasLang, hasT, looksRendered };
}

async function main() {
  let report = '# Phase B i18n orphan audit\n\n';
  report += 'Generated by `scripts/audit-tr-orphans.mjs`.\n\n';
  report += 'A file is an **orphan** if it renders user-facing text but has no `useLanguage` / `language ===` / `t()` wiring.\n\n';

  const summary = [];

  for (const [family, { pages }] of Object.entries(FAMILIES)) {
    report += `## ${family}\n\n`;
    let familyOrphans = 0;
    let familyMissing = 0;

    for (const pageBase of pages) {
      const pagePath = path.join(PAGES_DIR, `${pageBase}.tsx`);
      let pageStatus = '';
      let pageSrc = '';
      try {
        pageSrc = await fs.readFile(pagePath, 'utf8');
      } catch {
        report += `- **${pageBase}.tsx** — ⚠️ file not found\n`;
        familyMissing++;
        continue;
      }
      const { hasLang, hasT } = classify(pageSrc);
      if (!hasLang && !hasT) {
        pageStatus = '🔴 page has NO i18n wiring';
        familyOrphans++;
      } else if (!hasT && hasLang) {
        pageStatus = '🟡 inline ternaries only (refactor candidate)';
      } else {
        pageStatus = '🟢 uses t()';
      }
      report += `- **${pageBase}.tsx** — ${pageStatus}\n`;

      // Find interior component dir referenced by this page (look for unique component imports).
      const importMatches = [...pageSrc.matchAll(/from ['"]@\/components\/([^/'"]+)\/([^'"]+)['"]/g)];
      const SHARED_DIRS = new Set(['ui', 'seo', 'modern']);
      const interiorDirs = new Set(
        importMatches.map((m) => m[1]).filter((d) => !SHARED_DIRS.has(d))
      );
      for (const dir of interiorDirs) {
        const compDir = path.join(COMPONENTS_DIR, dir);
        const files = await walkComponents(compDir);
        if (!files.length) continue;
        const orphans = [];
        for (const f of files) {
          const src = await fs.readFile(f, 'utf8');
          const c = classify(src);
          if (!c.hasLang && !c.hasT && c.looksRendered) {
            orphans.push(path.relative(ROOT, f));
          }
        }
        if (orphans.length) {
          report += `    - dir \`components/${dir}\` orphans (${orphans.length}):\n`;
          for (const o of orphans) report += `      - ${o}\n`;
          familyOrphans += orphans.length;
        }
      }
    }
    summary.push(`- **${family}** — ${familyOrphans} orphan file(s)` + (familyMissing ? `, ${familyMissing} missing page(s)` : ''));
    report += '\n';
  }

  report = report.replace('\n\n## ', '\n\n## Summary\n\n' + summary.join('\n') + '\n\n## ');

  const outDir = path.join(ROOT, 'tmp');
  await fs.mkdir(outDir, { recursive: true });
  const outPath = path.join(outDir, 'i18n-tr-orphans.md');
  await fs.writeFile(outPath, report);
  console.log(`wrote ${path.relative(ROOT, outPath)}`);
  console.log(summary.join('\n'));
}

main();
